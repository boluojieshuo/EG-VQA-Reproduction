def make_video(path: Path, frames: int = 30, fps: int = 10, size=(64, 48)) -> Path:
    writer = cv2.VideoWriter(str(path), cv2.VideoWriter_fourcc(*"MJPG"), fps, size)
    assert writer.isOpened(), "OpenCV could not open a video writer"
    for index in range(frames):
        frame = np.full((size[1], size[0], 3), index * 7 % 255, dtype=np.uint8)
        writer.write(frame)
    writer.release()
    return path


def test_format_mmss():
    assert vc.format_mmss(0) == "00:00"
    assert vc.format_mmss(65.4) == "01:05"
    assert vc.format_mmss(3725) == "62:05"
    assert vc.format_mmss(-3) == "00:00"


@pytest.mark.parametrize(
    "total,num,expected_len",
    [(0, 32, 0), (10, 32, 10), (100, 5, 5)],
)
def test_sample_frame_indices(total, num, expected_len):
    indices = vc.sample_frame_indices(total, num)
    assert len(indices) == expected_len
    if total > 0:
        assert indices[0] == 0 and indices[-1] <= total - 1


def test_sample_frame_indices_uniform():
    indices = vc.sample_frame_indices(1000, 5)
    assert indices == [0, 250, 500, 749, 999]


def test_resize_if_needed_small_image_untouched():
    from PIL import Image

    image = Image.new("RGB", (100, 80))
    assert vc.resize_if_needed(image, max_pixels=10_000).size == (100, 80)


def test_resize_if_needed_large_image_downscaled():
    from PIL import Image

    image = Image.new("RGB", (1000, 800))
    resized = vc.resize_if_needed(image, max_pixels=100_000)
    assert resized.width * resized.height <= 110_000
    assert resized.width / resized.height == pytest.approx(1000 / 800, rel=0.01)


def test_draw_timestamp_returns_rgb():
    from PIL import Image

    image = Image.new("RGB", (320, 240), color=(0, 0, 0))
    result = vc.draw_timestamp(image, "00:05")
    assert result.mode == "RGB"
    # The top-right corner should now contain non-black pixels.
    assert np.asarray(result)[:20, -80:].max() > 0


def test_extract_frames_from_synthetic_video(tmp_path):
    video = make_video(tmp_path / "synthetic.mp4", frames=30, fps=10)
    out = tmp_path / "frames"
    vc.extract_frames_with_timestamps(video, out, num_frames=5)
    saved = sorted((out / "synthetic").glob("*.png"))
    assert len(saved) == 5
    assert [p.name for p in saved] == [f"synthetic_f{i:02d}.png" for i in range(5)]
    for path in saved:
        from PIL import Image

        with Image.open(path) as image:
            assert image.mode == "RGB"


def test_extract_missing_video_is_skipped(tmp_path):
    out = tmp_path / "frames"
    vc.extract_frames_with_timestamps(tmp_path / "does_not_exist.mp4", out, num_frames=5)
    produced = list(out.rglob("*.png")) if out.exists() else []
    assert produced == []


def test_extract_twice_overwrites_cleanly(tmp_path):
    video = make_video(tmp_path / "syn2.mp4", frames=20, fps=10)
    out = tmp_path / "frames"
    vc.extract_frames_with_timestamps(video, out, num_frames=4)
    first = {p.name: p.stat().st_size for p in (out / "syn2").glob("*.png")}
    vc.extract_frames_with_timestamps(video, out, num_frames=4)
    second = {p.name: p.stat().st_size for p in (out / "syn2").glob("*.png")}
    assert first == second and len(second) == 4


