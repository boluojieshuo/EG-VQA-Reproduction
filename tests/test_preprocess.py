def test_write_parquet_shards_roundtrip(tmp_path):
    import pyarrow.parquet as pq

    rows = [
        {"images": [b"a", b"b"], "problem": "<image>q", "answer": "{}"},
        {"images": [b"c"], "problem": "<image>r", "answer": "{}"},
        {"images": [], "problem": "s", "answer": "{}"},
    ]
    ptp.write_parquet_shards(rows, tmp_path / "out", shard_size=2)
    files = sorted((tmp_path / "out").glob("part-*.parquet"))
    assert len(files) == 2
    total = sum(pq.read_table(path).num_rows for path in files)
    assert total == 3


def test_write_empty_rows_raises(tmp_path):
    with pytest.raises(ValueError):
        ptp.write_parquet_shards([], tmp_path / "out")
